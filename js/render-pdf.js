// Native PDF report renderer (jsPDF + autoTable). A4, fixed margins, page numbers, full-resolution photos.
import { T, hex, clean, loadPdfLibs, rasterize } from './theme.js';
import { CAT_COLORS, VERSION } from './config.js';
import {checkJob,yieldJob,photoReader} from './photo-jobs.js';
import { fileBase } from './model.js';

export const PG={ w:210, h:297, ml:18, mr:18, mt:24, mb:18 };
export const CW=PG.w-PG.ml-PG.mr;
const fill=(d,h)=>d.setFillColor(...hex(h)), ink=(d,h)=>d.setTextColor(...hex(h)), draw=(d,h)=>d.setDrawColor(...hex(h));

export async function newDoc(){ const {jsPDF}=await loadPdfLibs(); return new jsPDF({unit:'mm',format:'a4',compress:true}); }

// header/footer on every page except the first (cover); returns nothing
export function frame(doc,{left,right,footLeft,skipFirst=true,noHeaderFirst=false}){
  const n=doc.getNumberOfPages();
  for(let i=skipFirst?2:1;i<=n;i++){
    doc.setPage(i);
    doc.setFont('helvetica','normal'); doc.setFontSize(7.5); ink(doc,T.muted);
    if(!(noHeaderFirst&&i===1)){ doc.text(clean(left||''),PG.ml,12); doc.text(clean(right||''),PG.w-PG.mr,12,{align:'right'});
    draw(doc,T.accent); doc.setLineWidth(0.5); doc.line(PG.ml,14,PG.w-PG.mr,14); }
    draw(doc,T.line); doc.setLineWidth(0.2); doc.line(PG.ml,PG.h-13,PG.w-PG.mr,PG.h-13);
    doc.text(clean(footLeft||''),PG.ml,PG.h-9); doc.text(`Page ${i} of ${n}`,PG.w-PG.mr,PG.h-9,{align:'right'});
  }
}

export function band(doc,{line1,line2,logo,h=58}){
  fill(doc,T.navy); doc.rect(0,0,PG.w,h,'F'); fill(doc,T.accent); doc.rect(0,h,PG.w,2.2,'F');
  doc.setFont('helvetica','bold'); doc.setFontSize(10); ink(doc,'#F2B79B'); doc.text(clean((line1||'SITE PROGRESS REPORT').toUpperCase()),PG.ml,h/2-2);
  doc.setFont('helvetica','normal'); doc.setFontSize(10.5); ink(doc,'#FFFFFF'); doc.text(clean(line2||''),PG.ml,h/2+5);
  if(logo){ try{ const p=doc.getImageProperties(logo); const lh=16, lw=Math.min(40,lh*p.width/p.height); fill(doc,'#FFFFFF'); doc.roundedRect(PG.w-PG.mr-lw-4,h/2-lh/2-2,lw+4,lh+4,1.5,1.5,'F'); doc.addImage(logo,'PNG',PG.w-PG.mr-lw-2,h/2-lh/2,lw,lh); }catch(_){} }
}

export async function renderPdf(model,{getFull,onProgress,signal,strictPhotos=false}={}){
  checkJob(signal);
  const readPhotos=photoReader(model.photos,getFull,{signal,onProgress});
  const doc=await newDoc(); const P=model.project; const say=(t)=>onProgress&&onProgress(t);
  const base=fileBase(model);
  doc.setProperties({title:`${model.no} ${model.title}`,subject:model.period,author:(model.signoff&&model.signoff.preparedName)||'',creator:'SiteBoard v'+VERSION});

  // ---------- cover
  band(doc,{line1:P.consultant||'Site progress report',line2:P.team,logo:P.logo});
  let y=82; doc.setFont('helvetica','normal'); doc.setFontSize(10.5); ink(doc,T.muted);
  doc.text(doc.splitTextToSize(clean(P.title),CW),PG.ml,y); y+=doc.splitTextToSize(clean(P.title),CW).length*5;
  ink(doc,T.ink); doc.setFontSize(11); doc.text(clean(P.subtitle),PG.ml,y); y+=22;
  doc.setFont('helvetica','bold'); doc.setFontSize(26); ink(doc,T.navy);
  const tl=doc.splitTextToSize(clean(model.title.toUpperCase()),CW); doc.text(tl,PG.ml,y); y+=tl.length*11;
  fill(doc,T.accent); doc.rect(PG.ml,y-4,28,1.4,'F'); y+=6;
  doc.setFontSize(15); ink(doc,T.accent); doc.text(clean(model.period),PG.ml,y); y+=14;
  const meta=[['Report no.',model.no],['Reporting period',model.period],['Section of works',P.chainage]];
  if(P.contractor) meta.push(['Contractor',P.contractor]);
  meta.push(['Prepared by',(model.signoff.preparedName||'')+(model.signoff.preparedTitle?', '+model.signoff.preparedTitle:'')],['Date issued',model.issued]);
  doc.autoTable({startY:y,body:meta.map(r=>r.map(clean)),theme:'plain',margin:{left:PG.ml,right:PG.mr},styles:{fontSize:10,cellPadding:{top:2.2,bottom:2.2,left:0,right:3},textColor:hex(T.ink)},
    columnStyles:{0:{cellWidth:42,textColor:hex(T.muted)},1:{fontStyle:'bold'}},didDrawCell:(d)=>{ if(d.column.index===1||d.column.index===0){ draw(doc,T.line); doc.setLineWidth(0.2); doc.line(d.cell.x,d.cell.y+d.cell.height,d.cell.x+d.cell.width,d.cell.y+d.cell.height); } }});
  doc.setFont('helvetica','normal'); doc.setFontSize(8); ink(doc,T.muted);
  doc.text(doc.splitTextToSize('Source: Site Daily Photo Reports submitted by site personnel (IOW / ARE). Generated by SiteBoard v'+VERSION+'.',CW),PG.ml,PG.h-20);

  // ---------- body
  doc.addPage(); y=PG.mt;
  const room=(h)=>{ if(y+h>PG.h-PG.mb){ doc.addPage(); y=PG.mt; return true; } return false; };
  const text=(s,{size=9.5,style='normal',color=T.ink,gap=2}={})=>{
    doc.setFont('helvetica',style); doc.setFontSize(size); ink(doc,color); const lh=size*0.43;
    const lines=doc.splitTextToSize(clean(s),CW);
    for(const ln of lines){ room(lh); doc.text(ln,PG.ml,y+lh*0.8); y+=lh; } y+=gap; };
  const legendRow=(cats)=>{ doc.setFont('helvetica','normal'); doc.setFontSize(7.5); let x=PG.ml; room(6);
    for(const c of cats){ const w=doc.getTextWidth(clean(c))+8; if(x+w>PG.w-PG.mr){ x=PG.ml; y+=4.5; room(5); } fill(doc,(CAT_COLORS[c]||CAT_COLORS.Other)[0]); doc.rect(x,y-2.4,2.6,2.6,'F'); ink(doc,T.muted); doc.text(clean(c),x+4,y); x+=w+3; }
    y+=6; };

  say('Drawing charts…');
  const charts=new Map();
  for(const b of model.blocks) if(b.t==='chart') charts.set(b,await rasterize(b.svg,3));

  for(const b of model.blocks){
    await yieldJob(signal);
    if(b.t==='h2'){ room(34); y+=3; doc.setFont('helvetica','bold'); doc.setFontSize(12.5); ink(doc,T.navy); doc.text(clean(b.x),PG.ml,y+4); y+=6.5; fill(doc,T.accent); doc.rect(PG.ml,y,CW,0.5,'F'); y+=4; }
    else if(b.t==='h3'){ room(26); y+=1; text(b.x,{size:10.5,style:'bold',color:T.accent,gap:1.5}); }
    else if(b.t==='p') text(b.x,{});
    else if(b.t==='note') text(b.x,{size:8,color:T.muted,gap:3});
    else if(b.t==='kpi'){
      room(22); const n=b.items.length, gw=3, w=(CW-gw*(n-1))/n;
      b.items.forEach(([v,l],i)=>{ const x=PG.ml+i*(w+gw); fill(doc,T.bg); doc.roundedRect(x,y,w,18,1.5,1.5,'F'); fill(doc,T.accent); doc.rect(x,y,1.2,18,'F');
        doc.setFont('helvetica','bold'); doc.setFontSize(16); ink(doc,T.navy); doc.text(clean(String(v)),x+5,y+8.5);
        doc.setFont('helvetica','normal'); doc.setFontSize(7.5); ink(doc,T.muted); doc.text(clean(l),x+5,y+14); });
      y+=22; }
    else if(b.t==='chart'){
      const r=charts.get(b); const vw=Math.min(CW,CW*r.w/720), vh=vw*r.h/r.w; room(vh+4);
      doc.addImage(r.url,'PNG',PG.ml,y,vw,vh,undefined,'FAST'); y+=vh+2; if(b.cats) legendRow(b.cats); else y+=2; }
    else if(b.t==='table'){ room(b.rows.length>6?42:14); table(doc,b,y,(ny)=>{ y=ny; }); }
  }

  // ---------- photographic record
  if(model.photos.length){
    doc.addPage(); y=PG.mt; doc.setFont('helvetica','bold'); doc.setFontSize(12.5); ink(doc,T.navy); doc.text('Photographic record',PG.ml,y+4); y+=6.5; fill(doc,T.accent); doc.rect(PG.ml,y,CW,0.5,'F'); y+=5;
    const gw=6, bw=(CW-gw)/2, bh=bw*0.75;
    for(let i=0;i<model.photos.length;i+=2){
      say(`Placing photos… ${i}/${model.photos.length}`);await yieldJob(signal);
      const pair=model.photos.slice(i,i+2);
      const imgs=new Map();for(const p of pair){try{const m=await readPhotos(p.report,[p.item]);const im=m.get(p.item.no);if(strictPhotos&&!im?.url)throw Error(`Photo unavailable: ${p.report.ref} #${p.item.no}`);imgs.set(p.report.ref+'#'+p.item.no,im);}catch(e){if(strictPhotos||e.name==='AbortError')throw e;}}checkJob(signal);
      doc.setFontSize(8.5); const caps=pair.map(p=>{ const lines=[]; doc.setFont('helvetica','bold'); doc.splitTextToSize(clean(p.cap),bw).forEach(l=>lines.push([l,'bold',8.5,T.ink]));
        doc.setFont('helvetica','normal'); doc.splitTextToSize(clean(p.sub),bw).forEach(l=>lines.push([l,'normal',8,T.ink]));
        if(p.rem){ doc.setFont('helvetica','italic'); doc.splitTextToSize(clean(p.rem),bw).slice(0,3).forEach(l=>lines.push([l,'italic',8,T.ink])); }
        doc.setFont('helvetica','normal'); doc.splitTextToSize(clean(p.by),bw).forEach(l=>lines.push([l,'normal',7,T.muted])); return lines; });
      const ch=Math.max(...caps.map(c=>c.length))*3.5+2;
      room(bh+ch+5);
      pair.forEach((p,k)=>{ const x=PG.ml+k*(bw+gw);
        fill(doc,'#EEF1F3'); doc.rect(x,y,bw,bh,'F');
        const im=imgs.get(p.report.ref+'#'+p.item.no);
        if(im&&im.url){ const ar=im.w/im.h; let w=bw,h=bw/ar; if(h>bh){ h=bh; w=bh*ar; } try{ doc.addImage(im.url,'JPEG',x+(bw-w)/2,y+(bh-h)/2,w,h,undefined,'FAST'); }catch(e){if(strictPhotos)throw Error(`Cannot place photo: ${p.report.ref} #${p.item.no}: ${e.message}`);} }
        else { doc.setFont('helvetica','normal'); doc.setFontSize(8); ink(doc,T.muted); doc.text('Photo not available',x+bw/2,y+bh/2,{align:'center'}); }
        let cy=y+bh+3.5; for(const [l,st,sz,col] of caps[k]){ doc.setFont('helvetica',st); doc.setFontSize(sz); ink(doc,col); doc.text(l,x,cy); cy+=3.5; } });
      y+=bh+ch+4;
    }
  }

  // ---------- sign-off
  room(40); y+=8; const sw=(CW-12)/3;
  model.sign.forEach(([l,n,t],i)=>{ const x=PG.ml+i*(sw+6); draw(doc,T.ink); doc.setLineWidth(0.3); doc.line(x,y+16,x+sw,y+16);
    doc.setFont('helvetica','bold'); doc.setFontSize(8.5); ink(doc,T.navy); doc.text(clean(l),x,y+4);
    doc.setFont('helvetica','normal'); ink(doc,T.ink); doc.text(clean(n||''),x,y+20); ink(doc,T.muted); doc.setFontSize(7.5); doc.text(clean(t||''),x,y+24); doc.text('Date:',x,y+29); });

  frame(doc,{left:P.title+' — '+P.subtitle,right:model.no,footLeft:`Generated by SiteBoard v${VERSION} · ${model.issued}`});
  say('Finishing…');
  await yieldJob(signal);
  return { blob:doc.output('blob'), pages:doc.getNumberOfPages(), name:base+'.pdf', base };
}

function table(doc,b,y0,setY){
  const n=b.head.length; const ncol=b.head.length;
  const cs={}; const widths=b.widths;
  if(b.matrix){ cs[0]={cellWidth:46,halign:'left'}; for(let i=1;i<ncol-1;i++) cs[i]={cellWidth:'auto',halign:'center'}; cs[ncol-1]={cellWidth:9,halign:'right',fontStyle:'bold'}; }
  else if(widths) widths.forEach((w,i)=>cs[i]={cellWidth:CW*w});
  (b.num||[]).forEach(i=>cs[i]=Object.assign(cs[i]||{},{halign:'right'}));
  const body=b.rows.map(r=>{
    if(r.grp) return [{content:clean(r.grp),colSpan:ncol,styles:{fillColor:hex(T.soft),fontStyle:'bold',textColor:hex(T.navy)}}];
    return r.map((c,i)=>{ if(c&&typeof c==='object'){ const st={}; if(c.bg) st.fillColor=hex('#'+c.bg); if(c.fg) st.textColor=hex('#'+c.fg); return {content:clean(c.x),styles:st}; } return clean(c); }); });
  doc.autoTable({startY:y0,head:[b.head.map(clean)],body,margin:{left:PG.ml,right:PG.mr,top:PG.mt,bottom:PG.mb},theme:'grid',rowPageBreak:'avoid',
    styles:{font:'helvetica',fontSize:b.matrix?6.5:8,cellPadding:b.matrix?0.7:1.6,lineColor:hex(T.line),lineWidth:0.15,textColor:hex(T.ink),overflow:'linebreak',valign:'middle'},
    headStyles:{fillColor:hex(T.navy),textColor:255,fontStyle:'bold',halign:b.center?'center':'left'},alternateRowStyles:{fillColor:hex('#FAFBFC')},
    columnStyles:cs,
    didParseCell:(d)=>{ if(d.section==='head'&&b.num&&b.num.includes(d.column.index)) d.cell.styles.halign='right'; if(d.section==='head'&&b.matrix&&d.column.index===0) d.cell.styles.halign='left'; if(b.matrix&&d.section==='body'&&d.column.index>0&&d.column.index<ncol-1) d.cell.styles.halign='center'; },
    didDrawPage:()=>{} });
  setY(doc.lastAutoTable.finalY+4);
}
