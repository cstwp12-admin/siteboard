import { CAT_ORDER, PROJECT } from './config.js';
import * as A from './analysis.js';
import { esc, setPrint, catColor, dayColumns, hbar, strip, legend, weekBars } from './charts.js';

const nf=(n)=>Number(n).toLocaleString('en-GB');
const dash=(s)=>s&&s!=='-'?esc(s):'–';

export function periodFor(type, anchor){
  if(type==='weekly'){ const f=A.mondayOf(anchor); return { from:f, to:A.addDays(f,6) }; }
  const d=A.fromIso(anchor); const f=A.iso(new Date(d.getFullYear(),d.getMonth(),1)); const t=A.iso(new Date(d.getFullYear(),d.getMonth()+1,0)); return { from:f, to:t };
}
export function defaultNo(type, from){
  if(type==='weekly'){ const w=A.isoWeek(from); return `CST-WSR-${w.year}-W${String(w.week).padStart(2,'0')}`; }
  const [y,m]=from.split('-'); return `CST-MSR-${y}-${m}`;
}

export function narrative(type, ctx){
  const { reports, rows, days, wdays, mx, wx, bins } = ctx;
  if(!reports.length) return 'No site daily photo reports were received for this period.';
  const people=new Set(reports.map(r=>r.code)).size;
  const cats=A.count(rows,r=>r.cat).filter(c=>c[0]!=='Other').slice(0,3).map(c=>c[0].toLowerCase());
  const zones=[...new Set(rows.map(r=>r.zone).filter(Boolean))].sort();
  const rain=wx.filter(w=>w.rain).length;
  const rf=A.rfiList(rows).length;
  let s=`During the ${type==='weekly'?'week':'month'} of ${A.fmtDate(ctx.from)} to ${A.fmtDate(ctx.to)}, ${reports.length} site daily photo report${reports.length>1?'s were':' was'} received from ${people} site personnel, covering ${wdays} working day${wdays>1?'s':''}. `;
  s+=`A total of ${rows.length} work item${rows.length>1?'s were':' was'} photographed`+(zones.length?` across ${zones.join(', ')}`:'')+(cats.length?`, mainly ${cats.join(', ')}`:'')+'. ';
  if(bins) s+=`Photographed works covered approximately ${nf((A.coveredLength(bins)/1000).toFixed(1))} km of the alignment (100 m resolution). `;
  if(rf) s+=`${rf} RFI reference${rf>1?'s were':' was'} recorded. `;
  if(ctx.idle) s+=`No site activity was reported on ${ctx.idle} day${ctx.idle>1?'s':''}. `;
  s+=rain? `Rain was recorded on ${rain} day${rain>1?'s':''}.` : 'No rain was recorded in the reports.';
  if(mx.rate!=null) s+=` Reporting compliance for expected personnel was ${Math.round(mx.rate*100)}% (${mx.got} of ${mx.exp} expected daily reports).`;
  return s;
}

export function buildReport(o){
  setPrint(true);
  try{ return _build(o); } finally { setPrint(false); }
}

function _build(o){
  const { type, from, to, all, settings, form, photos } = o;
  const today=A.iso(new Date());
  const reports=all.filter(r=>r.date>=from&&r.date<=to);
  const rows=A.works(A.flatten(reports));
  const idleDays=new Set(A.flatten(reports).filter(r=>r.cat==='No site activity').map(r=>r.date)).size;
  const days=A.dateRange(from,to);
  const wd=days.filter(d=>A.isWorkDay(d,settings));
  const mx=A.matrix(reports,days,settings,today);
  const wx=A.weatherDays(reports);
  const bins=A.binsFor(rows);
  const ctx={idle:idleDays,reports,rows,days,wdays:new Set(reports.map(r=>r.date)).size,mx,wx,bins,from,to};
  const P={...PROJECT,...(settings.project||{})};
  const S={...(settings.signoff||{})};
  const typeName=type==='weekly'?'WEEKLY SITE PROGRESS REPORT':'MONTHLY SITE PROGRESS REPORT';
  const periodTxt=`${A.fmtDate(from)} – ${A.fmtDate(to)}`;
  const title=form.title||typeName;
  let h='';

  // ---- cover
  h+=`<section class="paper"><div class="cover">
   <div class="band">${P.logo?`<img src="${P.logo}" alt="" style="float:right;height:36px;background:#fff;padding:3px 6px;border-radius:3px">`:''}<div style="font-size:10pt;letter-spacing:.08em;opacity:.85">${esc(P.consultant||'Site progress report').toUpperCase()}</div><div style="font-size:11pt;margin-top:2px">${esc(P.team)}</div></div>
   <div class="mid"><div class="muted" style="font-size:10.5pt">${esc(P.title)}</div><div style="font-size:11pt;margin-bottom:22px">${esc(P.subtitle)}</div>
   <h1>${esc(title)}</h1><div style="font-size:14pt;margin:8px 0 28px;color:#1f3b63">${esc(periodTxt)}</div>
   <table class="meta"><tbody>
    <tr><td>Report no.</td><td><b>${esc(form.no)}</b></td></tr>
    <tr><td>Reporting period</td><td>${esc(periodTxt)}</td></tr>
    <tr><td>Section of works</td><td>${esc(P.chainage)}</td></tr>
    ${P.contractor?`<tr><td>Contractor</td><td>${esc(P.contractor)}</td></tr>`:''}
    <tr><td>Prepared by</td><td>${esc(S.preparedName||'')}${S.preparedTitle?', '+esc(S.preparedTitle):''}</td></tr>
    <tr><td>Date issued</td><td>${esc(form.issued?A.fmtDate(form.issued):A.fmtDate(today))}</td></tr>
   </tbody></table></div>
   <div style="margin-top:auto" class="muted">Source: Site Daily Photo Reports submitted by CST site personnel (IOW / ARE). Generated by SiteBoard.</div>
  </div></section>`;

  h+='<section class="paper">';
  // ---- 1 summary
  const nar=narrative(type,ctx);
  h+=`<h2>1. Summary</h2><p>${esc(nar)}</p>`;
  const act=new Set(rows.map(r=>r.act)).size, ph=rows.filter(r=>r.item.photo).length, raindays=wx.filter(w=>w.rain).length;
  h+=`<div class="kp"><div><b>${reports.length}</b>Reports received</div><div><b>${rows.length}</b>Work items photographed</div><div><b>${act}</b>Distinct activities</div><div><b>${mx.rate!=null?Math.round(mx.rate*100)+'%':'–'}</b>Reporting compliance</div></div>`;
  const dayData=new Map(); for(const r of rows){ const d=dayData.get(r.date)||{}; d[r.cat]=(d[r.cat]||0)+1; dayData.set(r.date,d); }
  const usedCats=CAT_ORDER.filter(c=>rows.some(r=>r.cat===c));
  if(rows.length){ h+=`<h3>Work items photographed per day</h3>`+dayColumns(days,dayData,usedCats,{w:720,h:170})+legend(usedCats); }
  if(form.extra) h+=`<h3>Matters for attention</h3><p style="white-space:pre-wrap">${esc(form.extra)}</p>`;

  // ---- 2 reporting
  h+=`<h2>2. Site reporting status</h2>`;
  if(days.length<=31){
    h+=`<table><thead><tr><th>Personnel</th>${days.map(d=>`<th class="num" style="padding:4px 2px;text-align:center">${A.fromIso(d).getDate()}<br><span style="font-weight:400;font-size:7pt">${A.DOW[A.dow(d)].slice(0,2)}</span></th>`).join('')}<th class="num">Total</th></tr></thead><tbody>`;
    for(const r of mx.rows){ if(!r.tot && !r.p.expected) continue;
      h+=`<tr><td style="white-space:nowrap">${esc(r.p.name)} <span class="muted">(${esc(r.p.role||r.p.code)})</span></td>`+
        r.cells.map(c=>{ const n=c.rs.length; const miss=!n&&r.p.expected&&c.work&&c.past; return `<td style="text-align:center;padding:2px;${n?'background:#e3f3ea;':miss?'background:#fbe4e1;color:#b2271b;':!c.work?'background:#f3f2ef;':''}">${n?n:(miss?'✕':'')}</td>`; }).join('')+`<td class="num">${r.tot}</td></tr>`; }
    h+=`</tbody></table><p class="muted" style="font-size:8.5pt">Green = report(s) received; red ✕ = no report from an expected person on a working day; grey = non-working day.</p>`;
  } else h+='<p class="muted">Period too long to tabulate daily.</p>';

  // ---- 3 works by category/activity
  h+=`<h2>3. Summary of works photographed</h2>`;
  if(!rows.length) h+='<p>No works recorded.</p>';
  else{
    const catCounts=A.count(rows,r=>r.cat);
    h+=hbar(catCounts.map(([c,n])=>({label:c,value:n,color:catColor(c)})),{w:640,labelW:170});
    h+=`<table><thead><tr><th>Activity</th><th>BQ / QC ref.</th><th>Location(s)</th><th class="num">Items</th><th class="num">Days</th><th>Latest status</th></tr></thead><tbody>`;
    for(const c of CAT_ORDER){
      const cr=rows.filter(r=>r.cat===c); if(!cr.length) continue;
      h+=`<tr class="grp"><td colspan="6">${esc(c)} — ${cr.length} item${cr.length>1?'s':''}</td></tr>`;
      const by=new Map(); for(const r of cr){ const k=r.act.toLowerCase(); (by.get(k)||by.set(k,[]).get(k)).push(r); }
      const list=[...by.values()].sort((a,b)=>b.length-a.length);
      for(const g of list){
        const last=g.slice().sort((a,b)=>a.date.localeCompare(b.date)||a.item.no-b.item.no).at(-1);
        const bq=[...new Set(g.map(r=>r.bq).filter(Boolean))].join('; ');
        h+=`<tr><td>${esc(g[0].act)}</td><td>${dash(bq.length>60?bq.slice(0,58)+'…':bq)}</td><td>${esc(A.mergeLocs(g.map(r=>r.loc==='-'?'':r.loc),5))||'–'}</td><td class="num">${g.length}</td><td class="num">${new Set(g.map(r=>r.date)).size}</td><td>${esc(last.status||'–')}${last.pct!=null?' ('+last.pct+'%)':''}<br><span class="muted" style="font-size:8pt">${A.fmtShort(last.date)}</span></td></tr>`;
      }
    }
    h+='</tbody></table>';
  }

  // ---- 4 chainage & zone
  h+=`<h2>4. Progress by zone and chainage</h2>`;
  if(rows.some(r=>r.ch1!=null)){
    h+=`<p class="muted" style="font-size:9pt">Location of photographed works along ${esc(P.chainage)}. Colour shows the dominant activity category per 100 m; stronger colour = more records.</p>`+strip(bins,{w:720})+legend(usedCats);
    const zr=['Zone 1','Zone 2','Zone 3','Zone 4'];
    h+=`<table><thead><tr><th>Zone</th>${usedCats.map(c=>`<th class="num">${esc(c)}</th>`).join('')}<th class="num">Total</th></tr></thead><tbody>`;
    for(const z of zr){ const zrows=rows.filter(r=>r.zone===z); h+=`<tr><td>${z}</td>${usedCats.map(c=>`<td class="num">${zrows.filter(r=>r.cat===c).length||'–'}</td>`).join('')}<td class="num"><b>${zrows.length}</b></td></tr>`; }
    const nz=rows.filter(r=>!r.zone).length; if(nz) h+=`<tr><td>No chainage given</td>${usedCats.map(c=>`<td class="num">${rows.filter(r=>!r.zone&&r.cat===c).length||'–'}</td>`).join('')}<td class="num"><b>${nz}</b></td></tr>`;
    h+='</tbody></table>';
    const sc=new Map(); for(const r of rows) for(const code of A.structureCodes(r.structure)){ const e=sc.get(code)||{n:0,acts:new Set(),last:''}; e.n++; e.acts.add(r.act); if(r.date>e.last) e.last=r.date; sc.set(code,e); }
    if(sc.size){ h+=`<h3>Structures referenced</h3><table><thead><tr><th>Structure</th><th class="num">Items</th><th>Activities</th><th>Last</th></tr></thead><tbody>`+
      [...sc.entries()].sort((a,b)=>a[0].localeCompare(b[0],undefined,{numeric:true})).map(([k,e])=>`<tr><td>${k}</td><td class="num">${e.n}</td><td>${esc([...e.acts].slice(0,3).join('; '))}</td><td>${A.fmtShort(e.last)}</td></tr>`).join('')+'</tbody></table>'; }
  } else h+='<p>No chainage-referenced works in this period.</p>';

  // ---- 5 weather
  h+=`<h2>5. Weather</h2>`;
  if(wx.length){
    h+=`<table><thead><tr><th>Date</th><th>AM</th><th>PM</th><th>Rain</th></tr></thead><tbody>`+wx.map(w=>`<tr><td>${A.fmtDate(w.date,true)}</td><td>${esc([...w.am].join(' / '))||'–'}</td><td>${esc([...w.pm].join(' / '))||'–'}</td><td>${w.rain?'Yes':'–'}</td></tr>`).join('')+'</tbody></table>'+
      `<p>Rain recorded on <b>${raindays}</b> of ${wx.length} reported day${wx.length>1?'s':''}.</p>`;
  } else h+='<p>No weather data.</p>';

  // ---- 6 RFI
  const rf=A.rfiList(rows);
  h+=`<h2>6. RFI references</h2>`;
  h+= rf.length? `<table><thead><tr><th>RFI no.</th><th>Date(s)</th><th>Activity</th><th>Location</th><th class="num">Items</th></tr></thead><tbody>`+rf.map(e=>`<tr><td>${esc(e.rfi)}</td><td>${[...e.dates].sort().map(A.fmtShort).join(', ')}</td><td>${esc([...e.acts].join('; '))}</td><td>${esc([...e.locs].join('; '))||'–'}</td><td class="num">${e.n}</td></tr>`).join('')+'</tbody></table>' : '<p>No RFI referenced in the reports for this period.</p>';

  // ---- 7 remarks
  const rem=rows.filter(r=>r.remarks||/observ/i.test(r.status));
  const remShown=rem.filter(r=>r.remarks);
  h+=`<h2>7. Site observations and remarks</h2>`;
  h+= remShown.length? `<table><thead><tr><th>Date</th><th>Location</th><th>Activity</th><th>Status</th><th>Remarks</th><th>By</th></tr></thead><tbody>`+remShown.map(r=>`<tr><td>${A.fmtShort(r.date)}</td><td>${dash(r.loc)}</td><td>${esc(r.act)}</td><td>${esc(r.status||'–')}</td><td>${esc(r.remarks)}</td><td>${esc(r.code)}</td></tr>`).join('')+'</tbody></table>' : '<p>No remarks recorded in the reports.</p>';
  const obsOnly=rem.length-remShown.length; if(obsOnly) h+=`<p class="muted" style="font-size:9pt">${obsOnly} further item${obsOnly>1?'s are':' is'} marked “Observation” without remarks.</p>`;

  // ---- monthly extras
  if(type==='monthly'){
    const weeks=[]; let ws=A.mondayOf(from);
    while(ws<=to){ const we=A.addDays(ws,6); const a=ws<from?from:ws, b=we>to?to:we; const rr=reports.filter(r=>r.date>=a&&r.date<=b); const rw=rows.filter(r=>r.date>=a&&r.date<=b);
      const m2=A.matrix(rr,A.dateRange(a,b),settings,today); weeks.push({a,b,label:'W'+String(A.isoWeek(a).week).padStart(2,'0'),reports:rr.length,items:rw.length,rain:A.weatherDays(rr).filter(w=>w.rain).length,rate:m2.rate}); ws=A.addDays(ws,7); }
    h+=`<h2>8. Weekly breakdown</h2>`+weekBars(weeks.map(w=>({label:w.label,value:w.items})),{w:640})+`<p class="muted" style="font-size:9pt">Work items photographed per ISO week.</p>`+
      `<table><thead><tr><th>Week</th><th>Dates</th><th class="num">Reports</th><th class="num">Work items</th><th class="num">Rain days</th><th class="num">Compliance</th></tr></thead><tbody>`+
      weeks.map(w=>`<tr><td>${w.label}</td><td>${A.fmtShort(w.a)} – ${A.fmtShort(w.b)}</td><td class="num">${w.reports}</td><td class="num">${w.items}</td><td class="num">${w.rain}</td><td class="num">${w.rate!=null?Math.round(w.rate*100)+'%':'–'}</td></tr>`).join('')+'</tbody></table>';
  }

  // ---- next period / remarks
  const nn=type==='monthly'?9:8;
  if(form.next||form.remarks){
    h+=`<h2>${nn}. Planned works and other remarks</h2>`;
    if(form.next) h+=`<h3>Planned works for next ${type==='weekly'?'week':'month'}</h3><p style="white-space:pre-wrap">${esc(form.next)}</p>`;
    if(form.remarks) h+=`<h3>Other remarks</h3><p style="white-space:pre-wrap">${esc(form.remarks)}</p>`;
  }
  h+='</section>';

  // ---- photo record
  if(photos&&photos.length){
    h+=`<section class="paper" style="break-before:page"><h2 style="margin-top:0">Photographic record</h2><div class="figs">`+
      photos.map((p,i)=>`<div class="fig"><img src="${p.url}" alt=""><div><b>Photo ${i+1}</b> — ${esc(p.item.activity)}<br>${A.fmtDate(p.report.date)}${p.item.time?' '+esc(p.item.time):''} · ${p.item.location&&p.item.location!=='-'?esc(p.item.location):'location n/a'}${p.item.zone?' · '+p.item.zone:''}${p.item.remarks?'<br><i>'+esc(p.item.remarks)+'</i>':''}<br><span class="muted">${esc(p.report.reporter)}${p.report.role?', '+esc(p.report.role):''} · ${esc(p.report.ref)}</span></div></div>`).join('')+'</div></section>';
  }

  // ---- sign-off
  h+=`<section class="paper" style="padding-top:0"><div class="sign">`+
    [['Prepared by',S.preparedName,S.preparedTitle],['Checked by',S.checkedName,S.checkedTitle],['Reviewed / Approved by',S.approvedName,S.approvedTitle]].map(([l,n,t])=>`<div><b>${l}</b><br>${esc(n||'')}<br><span class="muted">${esc(t||'')}</span><br><span class="muted">Date:</span></div>`).join('')+`</div></section>`;
  return h;
}
