"""Generate the offline allowlist from shipped app files; run after building docs."""
from pathlib import Path
import re, json, hashlib, struct, zlib
app=Path(__file__).resolve().parent.parent
version=re.search(r"VERSION = '([\d.]+)'",(app/'js/config.js').read_text()).group(1)
# Small deterministic raster icons for browsers requiring PNG install icons.
def icon(size):
    rows=[]
    for y in range(size):
        row=bytearray([0])
        for x in range(size):
            a,b=x*512/size,y*512/size
            color=(20,33,43,255)
            if 64<=a<448 and 64<=b<448: color=(217,72,15,255)
            if (108<=a<=404 and 332<=b<=372) or any(abs(a-c)<=20 and top<=b<=352 for c,top in [(160,240),(256,160),(352,256)]): color=(255,255,255,255)
            row.extend(color)
        rows.append(bytes(row))
    def chunk(t,d): return struct.pack('>I',len(d))+t+d+struct.pack('>I',zlib.crc32(t+d)&0xffffffff)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',size,size,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows)))+chunk(b'IEND',b'')
for size in [192,512]: (app/f'icons/siteboard-{size}.png').write_bytes(icon(size))
paths=['index.html','manifest.webmanifest']
for directory in ['js','css','vendor','docs','icons']:
    paths += [p.relative_to(app).as_posix() for p in (app/directory).rglob('*') if p.is_file()]
paths=sorted(paths)
fingerprint=hashlib.sha256(b''.join((app/p).read_bytes() for p in paths)).hexdigest()[:16]
source='''// Generated by tools/build_shell.py. Only app assets are cached, never reports or settings.
const VERSION=__VERSION__, ASSETS=__ASSETS__;
const PREFIX='siteboard-shell:'+self.registration.scope+':', CACHE=PREFIX+VERSION;
const allowed=new Set(ASSETS.map(p=>new URL(p,self.registration.scope).href));
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS.map(p=>new Request(new URL(p,self.registration.scope),{cache:'reload'}))))));
self.addEventListener('activate',event=>event.waitUntil((async()=>{for(const k of await caches.keys())if(k.startsWith(PREFIX)&&k!==CACHE)await caches.delete(k);await self.clients.claim();})()));
self.addEventListener('message',event=>{if(event.data?.type==='ACTIVATE_UPDATE')self.skipWaiting();});
self.addEventListener('fetch',event=>{
  if(event.request.method!=='GET')return;
  const url=new URL(event.request.url);if(url.origin!==self.location.origin)return;
  const shell=new URL('index.html',self.registration.scope).href;
  const isHome=event.request.mode==='navigate'&&(url.pathname===new URL(self.registration.scope).pathname||url.pathname===new URL(shell).pathname);
  if(!isHome&&!allowed.has(url.href))return;
  event.respondWith(caches.open(CACHE).then(async cache=>{const hit=await cache.match(isHome?shell:event.request);return hit||fetch(event.request);}));
});
'''.replace('__VERSION__',json.dumps(version+'-'+fingerprint)).replace('__ASSETS__',json.dumps(paths))
(app/'sw.js').write_text(source,encoding='utf-8')
print(f'Offline shell {version}: {len(paths)} assets, {fingerprint}')
